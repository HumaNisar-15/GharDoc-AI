def current_lang():
    try:
        import streamlit as st
        lang = st.session_state.get("lang", config.DEFAULT_LANG)
    except Exception:
        lang = config.DEFAULT_LANG
    return lang if lang in LANG_INDEX else config.DEFAULT_LANG


def pick(entry, lang=None):
    """Pick the right language from a (English, Roman Urdu[, Urdu]) tuple.
    Urdu falls back to Roman Urdu when a 2-item tuple is used."""
    i = LANG_INDEX[lang or current_lang()]
    if i >= len(entry):
        i = len(entry) - 1
    return entry[i]


def t(key, lang=None):
    return pick(STR[key], lang)


def is_rtl(lang=None):
    return (lang or current_lang()) in config.RTL_LANGS
